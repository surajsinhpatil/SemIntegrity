#!/usr/bin/env python3
"""Run D4 — EXPLORATORY distributional analysis (§4.8.6, ADR-0024).

    MODEL=qwen25-3b sbatch --partition=gpu-short --exclude=csis.mn1,csis.cn2 \
        --gres=gpu:1 slurm/60_d4_distributional.sbatch

**D4 IS NOT A CONTRADICTION DETECTOR.** Its estimand is the mean pairwise
Jensen-Shannon divergence, within a constraint, between the candidate
distributions induced by semantically equivalent probes — a measure of
**distributional instability under paraphrase**. Instability is not
contradiction. D4 exposes no verdict, contributes to no PSCR and enters no H1
contrast.

PROMPTS ARE REUSED FROM THE PRIMARY RUN
---------------------------------------
Each response carries `provenance.rendered_prompt`, the exact string the model
saw (§4.6 logs it). D4 scores against those, so its distribution is conditioned
on the identical input. Re-rendering would risk a template or tokenizer drift
that silently changes the conditioning.

THE TEMPERATURE BAND COSTS NO EXTRA INFERENCE
---------------------------------------------
`T = 1` is the frozen primary (ADR-0024). The band `T in {0.5, 1, 2, 4}` is
computed from the SAME stored log-probabilities by
`distributional.temperature_band`, because `T` enters only in
`softmax(mean_logprob / T)` — arithmetic, not a forward pass. Every temperature
therefore sees identical model output, which is what makes the band a
sensitivity analysis rather than four experiments. Cross-`T` magnitude
comparison is forbidden.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from semintegrity.benchmark.loader import load_split
from semintegrity.detectors.d4.distributional import (
    PRIMARY_TEMPERATURE,
    SENSITIVITY_TEMPERATURES,
    D4Distributional,
    SoftmaxOverMeanLogprob,
    temperature_band,
)
from semintegrity.detectors.d4.scorer import TeacherForcedScorer
from semintegrity.inference.backend import assert_no_stub_responses
from semintegrity.inference.provenance import software_matrix
from semintegrity.schemas.response import RawResponse
from semintegrity.utils.config import load_config
from semintegrity.utils.hashing import sha256_file
from semintegrity.utils.io import read_jsonl
from semintegrity.utils.paths import data_path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", required=True)
    ap.add_argument("--model-config", required=True,
                    help="configs/models/<name>.yaml — the SAME model that generated --raw")
    ap.add_argument("--split", default="test")
    ap.add_argument("--out-dir", default="results/detectors/d4/raw")
    ap.add_argument("--device", default="auto")
    ap.add_argument("--limit-constraints", type=int, default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    assert_no_stub_responses(args.raw, context="the D4 distributional run")

    d4cfg = load_config("configs/detectors/d4_distributional.yaml").data
    dc = d4cfg["method"]["distribution_construction"]
    if dc["status"] != "RESOLVED":
        sys.exit(f"D4 distribution_construction is {dc['status']}; ADR-0024 resolves it")
    temperature = float(dc["temperature"])
    band = tuple(float(t) for t in dc["sensitivity_band"])
    if temperature != PRIMARY_TEMPERATURE or band != SENSITIVITY_TEMPERATURES:
        sys.exit(
            f"config says T={temperature} band={band}; the code constants are "
            f"T={PRIMARY_TEMPERATURE} band={SENSITIVITY_TEMPERATURES}. "
            "Refusing to run with two definitions of a preregistered quantity."
        )

    mcfg = load_config(args.model_config).data
    cons_list, _ = load_split(data_path("benchmark") / args.split)
    constraints = {c.constraint_id: c for c in cons_list}

    raws = [RawResponse.model_validate(r) for r in read_jsonl(args.raw)]
    if not raws:
        sys.exit(f"no responses in {args.raw}")
    model_id = raws[0].provenance.model_id
    if model_id != mcfg["model_id"]:
        sys.exit(
            f"--model-config is {mcfg['model_id']} but --raw was generated by "
            f"{model_id}. D4 must score with the SAME model that produced the "
            "responses, or the distribution is not that model's."
        )

    by_constraint: dict[str, list] = defaultdict(list)
    for r in raws:
        by_constraint[r.constraint_id].append(r)
    cids = sorted(by_constraint)
    if args.limit_constraints:
        cids = cids[: args.limit_constraints]

    # §4.8.6 scope: Track A only, closed candidate set.
    scoped = [c for c in cids if constraints[c].answer_space]
    print(f"model      : {model_id}")
    print(f"T (primary): {temperature}   band: {list(band)}")
    print(f"constraints: {len(scoped)} of {len(cids)} with a closed candidate set")
    missing_prompt = sum(
        1 for c in scoped for r in by_constraint[c]
        if not (r.provenance.rendered_prompt or "").strip()
    )
    if missing_prompt:
        sys.exit(
            f"{missing_prompt} response(s) carry no provenance.rendered_prompt. "
            "D4 must condition on the prompt the model actually saw; "
            "re-rendering would change the conditioning."
        )
    if args.dry_run:
        n = sum(len(by_constraint[c]) * len(constraints[c].answer_space) for c in scoped)
        print(f"\n--dry-run: {n} candidate scorings planned, nothing loaded.")
        return 0

    scorer = TeacherForcedScorer(
        model_id=mcfg["model_id"], revision=mcfg["revision"],
        dtype=mcfg.get("dtype", "bfloat16"), device=args.device,
    )
    scorer.load()
    print(f"loaded     : {scorer.name}\n")
    d4 = D4Distributional(
        scorer=scorer, builder=SoftmaxOverMeanLogprob(temperature=temperature)
    )

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    safe = model_id.replace("/", "__")
    archive = out_dir / f"{safe}.jsonl"
    done: set[str] = set()
    if archive.is_file():
        done = {
            json.loads(line)["constraint_id"]
            for line in archive.read_text().splitlines() if line.strip()
        }
        print(f"resuming: {len(done)} constraint(s) already analysed")

    written = 0
    with archive.open("a", encoding="utf-8") as fh:
        for n, cid in enumerate(scoped, start=1):
            if cid in done:
                continue
            c = constraints[cid]
            prompts = {r.probe_id: r.provenance.rendered_prompt for r in by_constraint[cid]}
            dists = [
                d4.distribution_for(pid, prompt, list(c.answer_space))
                for pid, prompt in sorted(prompts.items())
            ]
            analysis = d4.analyse(cid, prompts, list(c.answer_space))
            fh.write(json.dumps({
                "constraint_id": cid, "model_id": model_id,
                "n_probes": analysis.n_probes,
                "mean_pairwise_jsd": analysis.mean_pairwise_jsd,
                "max_pairwise_jsd": analysis.max_pairwise_jsd,
                "builder": analysis.builder, "scorer": analysis.scorer,
                "primary_temperature": temperature,
                # Stored so the band needs no re-scoring, ever.
                "mean_logprobs": {d.probe_id: list(d.mean_logprobs) for d in dists},
                "candidates": list(c.answer_space),
                "temperature_band": temperature_band(cid, dists, temperatures=band,
                                                     primary=temperature),
                "is_detector": False,
                "interpretation_limit": analysis.interpretation_limit,
            }, sort_keys=True) + "\n")
            written += 1
            if n % 10 == 0 or n == len(scoped):
                print(f"  analysed {n}/{len(scoped)} constraints", flush=True)

    rows = [json.loads(line) for line in archive.read_text().splitlines() if line.strip()]
    defined = [r["mean_pairwise_jsd"] for r in rows if r["mean_pairwise_jsd"] is not None]
    summary = {
        "generated_at_utc": dt.datetime.now(dt.UTC).isoformat(),
        "model_id": model_id, "raw_file": args.raw,
        "raw_sha256": sha256_file(args.raw),
        "primary_temperature": temperature,
        "sensitivity_band": list(band),
        "band_reused_one_scoring_run": True,
        "n_constraints": len(rows),
        "mean_jsd_at_primary_T": (sum(defined) / len(defined)) if defined else None,
        "is_contradiction_detector": False,
        "exposes_verdict": False,
        "contributes_to_pscr": False,
        "cross_temperature_magnitude_comparison": "FORBIDDEN (ADR-0024)",
        "scope_limits": d4cfg["scope_limits"],
        "human_gold": "NONE — and D4 would not use it; it measures instability",
        "software": software_matrix(),
    }
    (out_dir / f"{safe}.summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True, default=str) + "\n"
    )
    print(f"\nwrote {written} constraint analysis/analyses -> {archive}")
    print(f"mean pairwise JSD at T={temperature}: {summary['mean_jsd_at_primary_T']}")
    print("\nD4 is EXPLORATORY. No verdict, no contradiction count, no PSCR.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
