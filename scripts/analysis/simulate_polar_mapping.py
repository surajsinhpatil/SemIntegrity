#!/usr/bin/env python3
"""OFFLINE what-if: recompute a finished pilot under Q21's polarity mapping.

    python scripts/analysis/simulate_polar_mapping.py --raw results/raw/pilot/qwen25-3b.jsonl

READ-ONLY, and it changes NO production code. The canonicaliser, D1 and the
schemas are untouched; the proposed mapping is implemented here as an overlay so
the consequences can be measured before anything is decided. No new inference:
this reuses the responses already generated by job 11969.

WHAT THE MAPPING IS
-------------------
Verified against the pilot benchmark before being written:

  * a probe is POLAR iff `expected_answer` is YES/NO. On boolean constraints all
    48 probes are polar; on entity and date constraints 18 of 24 are.
  * every polar probe on a non-boolean constraint names the constraint's gold
    answer in its text (36/36, no exceptions), so the candidate it asserts is
    the gold answer `g`.
  * `expected_answer` follows polarity exactly: affirmative -> YES, negated ->
    NO (36/36).

For a polar probe on a non-boolean constraint, the model's YES/NO is a claim
about the proposition the probe asserts:

    affirms_g = (polarity == affirmative) == (response == YES)

      affirmative + YES -> the answer IS g          -> DEFINITE(g)
      affirmative + NO  -> the answer is NOT g      -> NEGATED(g)
      negated     + YES -> "it is false that ... g" -> NEGATED(g)
      negated     + NO  -> double negation          -> DEFINITE(g)

NEGATED(g) is the "not-X" state the researcher approved on 2026-09-25:
it CONTRADICTS a definite g, and is compatible with a definite answer other than
g and with another NEGATED. Pair semantics, mirroring D1's "differ = contradict":

    DEFINITE(x) vs DEFINITE(y) -> contradiction iff x != y
    DEFINITE(x) vs NEGATED(y)  -> contradiction iff x == y
    NEGATED(x)  vs NEGATED(y)  -> never (both are satisfiable together)

KNOWN LIMITATION, reported rather than hidden: a polar probe can only ever yield
`g` or `not-g`. It can never yield "Sydney". So polar probes detect only
g/not-g contradictions, never g/other-member ones. Every polar probe in this
pilot asserts the GOLD answer, so no polar probe tests a distractor.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from dataclasses import dataclass
from itertools import combinations

from semintegrity.benchmark.loader import load_split
from semintegrity.canonicalization.canonicaliser import canonicalise, normalise
from semintegrity.schemas.enums import ResponseLabel
from semintegrity.schemas.response import RawResponse
from semintegrity.utils.io import read_jsonl
from semintegrity.utils.paths import data_path

_YES = {"yes", "y", "true", "correct", "right", "affirmative"}
_NO = {"no", "n", "false", "incorrect", "wrong", "negative"}


def parse_yes_no(text: str) -> bool | None:
    """YES -> True, NO -> False, anything else -> None.

    Deliberately strict: only a leading yes/no token counts. A response that
    merely contains the word is not treated as a polar answer.
    """
    tokens = normalise(text).split()
    if not tokens:
        return None
    if tokens[0] in _YES:
        return True
    if tokens[0] in _NO:
        return False
    return None


@dataclass(frozen=True, slots=True)
class State:
    """A response's meaning after the proposed mapping."""

    kind: str  # DEFINITE | NEGATED | ABSTAIN | INVALID
    value: str | None = None

    @property
    def evaluable(self) -> bool:
        return self.kind in ("DEFINITE", "NEGATED")


def contradicts(a: State, b: State) -> bool:
    """Pair semantics for the approved not-X rule."""
    if a.kind == "DEFINITE" and b.kind == "DEFINITE":
        return a.value != b.value
    if a.kind == "DEFINITE" and b.kind == "NEGATED":
        return a.value == b.value
    if a.kind == "NEGATED" and b.kind == "DEFINITE":
        return b.value == a.value
    return False  # NEGATED vs NEGATED: jointly satisfiable


def map_response(raw, constraint, probe, current) -> tuple[State, str]:
    """Return the proposed state and a cause tag for the breakdown.

    Boolean constraints are NOT exempt. Every probe of a boolean constraint is
    polar, and a correct model answers YES to the affirmative form and NO to the
    negated form -- both meaning "the constraint holds". Recording those
    literally makes a perfectly consistent model score PSCR 0.571 on every
    boolean constraint. So the same normalisation applies, and it applies to
    responses the canonicaliser already labelled ANSWER, not only to INVALIDs.
    """
    if current.label is ResponseLabel.ABSTAIN:
        return State("ABSTAIN"), "already_ABSTAIN"
    if current.label not in (ResponseLabel.ANSWER, ResponseLabel.INVALID):
        return State("INVALID"), f"other_label_{current.label.value}"

    was_invalid = current.label is ResponseLabel.INVALID
    is_polar_probe = probe.expected_answer in ("YES", "NO")

    # --- boolean constraint: normalise "does the proposition hold?" ----------
    if constraint.answer_type.value == "boolean":
        b = parse_yes_no(raw.raw_text)
        if b is None:
            return State("INVALID"), "boolean_constraint_nonboolean_answer"
        affirms = (probe.polarity.value == "affirmative") == b
        cause = "polarity_mapped" if was_invalid else "polarity_normalised_boolean"
        return State("DEFINITE", "YES" if affirms else "NO"), cause

    # --- entity/date, open probe: unchanged ----------------------------------
    if not is_polar_probe:
        if was_invalid:
            return State("INVALID"), "open_probe_unrecognised_answer"
        return State("DEFINITE", current.canonical_answer), "already_ANSWER"

    # --- entity/date, polar probe: the Q21 mapping ---------------------------
    b = parse_yes_no(raw.raw_text)
    if b is None:
        if was_invalid:
            return State("INVALID"), "polar_probe_nonpolar_answer"
        return State("DEFINITE", current.canonical_answer), "already_ANSWER"

    affirms = (probe.polarity.value == "affirmative") == b
    g = constraint.gold_answer
    cause = "polarity_mapped" if was_invalid else "polarity_normalised_entity_date"
    return (State("DEFINITE", g) if affirms else State("NEGATED", g)), cause


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--raw", required=True)
    ap.add_argument("--split", default="pilot")
    args = ap.parse_args(argv)

    cons_list, probe_list = load_split(data_path("benchmark") / args.split)
    constraints = {c.constraint_id: c for c in cons_list}
    probes = {p.probe_id: p for p in probe_list}
    raws = [RawResponse.model_validate(r) for r in read_jsonl(args.raw)]

    base_labels: Counter[str] = Counter()
    new_kinds: Counter[str] = Counter()
    causes: Counter[str] = Counter()
    by_constraint: dict[str, list] = defaultdict(list)
    recovered_examples: list[str] = []

    for r in raws:
        c, p = constraints[r.constraint_id], probes[r.probe_id]
        cur = canonicalise(r, c)
        base_labels[cur.label.value] += 1
        state, cause = map_response(r, c, p, cur)
        new_kinds[state.kind] += 1
        if cur.label is ResponseLabel.INVALID:
            causes[cause] += 1
            if cause == "polarity_mapped" and len(recovered_examples) < 6:
                recovered_examples.append(
                    f"    {r.probe_id} [{p.polarity.value}] said={r.raw_text!r} "
                    f"-> {state.kind}({state.value})"
                )
        by_constraint[r.constraint_id].append((cur, state))

    n = len(raws)
    print(f"=== {n} responses from {args.raw} ===\n")

    print("--- Stage 0 labels: CURRENT (production canonicaliser) ---")
    for k, v in base_labels.most_common():
        print(f"  {k:10s} {v:4d}  {v / n:6.1%}")
    base_canon = base_labels.get("ANSWER", 0) + base_labels.get("ABSTAIN", 0)
    print(f"  canonicalisation rate : {base_canon / n:6.1%}   "
          f"{'PASS' if base_canon / n >= 0.95 else 'FAIL'} vs 95% CANON gate")

    print("\n--- Under the PROPOSED mapping (simulation only) ---")
    for k, v in new_kinds.most_common():
        print(f"  {k:10s} {v:4d}  {v / n:6.1%}")
    new_canon = n - new_kinds.get("INVALID", 0)
    print(f"  canonicalisation rate : {new_canon / n:6.1%}   "
          f"{'PASS' if new_canon / n >= 0.95 else 'FAIL'} vs 95% CANON gate")
    print(f"  recovered responses   : {base_labels.get('INVALID', 0) - new_kinds.get('INVALID', 0)}")

    print(f"\n--- What explains the {base_labels.get('INVALID', 0)} current INVALIDs? ---")
    for cause, v in causes.most_common():
        print(f"  {cause:42s} {v:4d}")
    if recovered_examples:
        print("\n  examples of polarity-mapped recoveries:")
        print("\n".join(recovered_examples))

    print("\n--- PSCR and D1 coverage, both ways (per constraint) ---")
    print(f"  {'constraint':16s} {'cur cov':>8s} {'cur PSCR':>9s} "
          f"{'new cov':>8s} {'new PSCR':>9s}")
    tot = {"cc": 0.0, "cp": 0.0, "nc": 0.0, "np": 0.0, "k": 0}
    for cid in sorted(by_constraint):
        rows = by_constraint[cid]
        cur_pairs = list(combinations([x for x, _ in rows], 2))
        cur_eval = [(a, b) for a, b in cur_pairs if a.is_evaluable and b.is_evaluable]
        cur_con = sum(a.canonical_answer != b.canonical_answer for a, b in cur_eval)
        new_pairs = list(combinations([s for _, s in rows], 2))
        new_eval = [(a, b) for a, b in new_pairs if a.evaluable and b.evaluable]
        new_con = sum(contradicts(a, b) for a, b in new_eval)
        cc = len(cur_eval) / len(cur_pairs)
        nc = len(new_eval) / len(new_pairs)
        cp = cur_con / len(cur_eval) if cur_eval else float("nan")
        np_ = new_con / len(new_eval) if new_eval else float("nan")
        print(f"  {cid:16s} {cc:8.3f} {cp:9.3f} {nc:8.3f} {np_:9.3f}")
        tot["cc"] += cc
        tot["nc"] += nc
        tot["k"] += 1
        if cur_eval:
            tot["cp"] += cp
        if new_eval:
            tot["np"] += np_
    k = tot["k"]
    print(f"\n  {'MEAN':16s} {tot['cc'] / k:8.3f} {tot['cp'] / k:9.3f} "
          f"{tot['nc'] / k:8.3f} {tot['np'] / k:9.3f}")
    # --- validity invariant --------------------------------------------------
    # A model that answers EVERY probe with that probe's expected_answer is by
    # definition perfectly self-consistent. Any PSCR above zero for such a model
    # is a measurement artifact, not inconsistency. This is a property of the
    # mapping and needs no model output, so it is computed from the benchmark.
    print("\n--- VALIDITY CHECK: PSCR for a hypothetical PERFECTLY CONSISTENT model ---")
    print("    (answers every probe with its own expected_answer; must be 0.000)")
    print(f"  {'constraint':16s} {'current':>9s} {'proposed':>9s}")
    cur_art = prop_art = 0.0
    for cid in sorted(by_constraint):
        c = constraints[cid]
        ps = [probes[p.probe_id] for p, _ in
              [(probes[r.probe_id], None) for r in raws if r.constraint_id == cid]]
        cur_vals = [p.expected_answer for p in ps]
        cur_c = sum(a != b for a, b in combinations(cur_vals, 2))
        prop: list[State] = []
        for p in ps:
            if p.expected_answer in ("YES", "NO"):
                b = p.expected_answer == "YES"
                affirms = (p.polarity.value == "affirmative") == b
                if c.answer_type.value == "boolean":
                    prop.append(State("DEFINITE", "YES" if affirms else "NO"))
                else:
                    g = c.gold_answer
                    prop.append(State("DEFINITE", g) if affirms else State("NEGATED", g))
            else:
                prop.append(State("DEFINITE", p.expected_answer))
        prop_c = sum(contradicts(a, b) for a, b in combinations(prop, 2))
        npairs = len(list(combinations(ps, 2)))
        print(f"  {cid:16s} {cur_c / npairs:9.3f} {prop_c / npairs:9.3f}")
        cur_art += cur_c / npairs
        prop_art += prop_c / npairs
    k2 = len(by_constraint)
    print(f"  {'MEAN ARTIFACT':16s} {cur_art / k2:9.3f} {prop_art / k2:9.3f}")
    if prop_art > 1e-9:
        print("  *** PROPOSED MAPPING FAILS THE INVARIANT -- do not adopt it ***")
    else:
        print("  proposed mapping scores a perfect model at 0.000, as it must.")

    print("\nNOTE: simulation only. No production code changed, no methodology adopted,")
    print("      the 95% CANON threshold and the preregistration are untouched.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
