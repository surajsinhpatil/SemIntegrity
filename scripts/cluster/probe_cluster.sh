#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# READ-ONLY cluster reconnaissance. Safe to run on the login node.
# Writes a report to docs/phase0/cluster_probe_<timestamp>.md and prints it.
#
# It does NOT: submit jobs, download anything, install anything, or write
# outside this repository.
#
#   bash scripts/cluster/probe_cluster.sh
# ---------------------------------------------------------------------------
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
OUT="${ROOT}/docs/phase0/cluster_probe_${STAMP}.md"
mkdir -p "$(dirname "$OUT")"

section() { printf '\n## %s\n\n```\n' "$1" >>"$OUT"; }
endsec()  { printf '```\n' >>"$OUT"; }
run()     { printf '$ %s\n' "$*" >>"$OUT"; "$@" >>"$OUT" 2>&1 || printf '(command unavailable or failed: %s)\n' "$*" >>"$OUT"; }

cat >"$OUT" <<EOF
# Cluster probe — ${STAMP}

Read-only reconnaissance for SemIntegrity. Generated by
\`scripts/cluster/probe_cluster.sh\`. Nothing was submitted, installed or
downloaded.
EOF

section "Identity and working directory"
run hostname -f
run whoami
run id
printf '$ pwd\n%s\n' "$(pwd)" >>"$OUT"
printf '$ echo "$HOME"\n%s\n' "$HOME" >>"$OUT"
endsec

section "Designated working directory"
WORKDIR="/nfs_home/users/yashsinha/H20250058_Suraj"
run ls -ld "$WORKDIR"
run test -w "$WORKDIR"
printf 'writable: %s\n' "$([ -w "$WORKDIR" ] && echo yes || echo NO)" >>"$OUT"
endsec

section "Storage and quota"
run df -h "$WORKDIR"
run df -h "$HOME"
run quota -s
run lfs quota -h "$WORKDIR"
endsec

section "Slurm — partitions"
run sinfo -o "%20P %5a %10l %6D %6t %N"
run sinfo -o "%20P %10l %20G %N" -e
endsec

section "Slurm — GPU generic resources"
run sinfo -o "%30N %10c %10m %25f %30G" -e
run scontrol show config
endsec

section "Slurm — my limits and accounts"
run sacctmgr show associations user="$(whoami)" format=Account,Partition,GrpTRES,MaxJobs,MaxSubmit,QOS -P
run sshare -U
run squeue -u "$(whoami)"
endsec

section "GPU visibility on this node (login node usually has none)"
run nvidia-smi
run nvidia-smi --query-gpu=name,memory.total,driver_version,compute_cap --format=csv
endsec

section "Software environment"
run module avail
run module list
run which python3 python conda mamba srun sbatch
run python3 -V
run nvcc --version
run which R Rscript
endsec

section "Network reachability (needed for Wikidata + HuggingFace caching)"
run env
printf '\n-- connectivity --\n' >>"$OUT"
for url in https://query.wikidata.org https://www.wikidata.org https://huggingface.co; do
  code=$(curl -s -o /dev/null -m 10 -w '%{http_code}' "$url" 2>/dev/null)
  printf '%-32s HTTP %s\n' "$url" "${code:-no-response}" >>"$OUT"
done
endsec

section "Existing environments / caches in the working directory"
run ls -la "$WORKDIR"
run du -sh "$WORKDIR"
endsec

printf '\n---\nProbe complete. Review, then fill configs/cluster/cluster.yaml.\n' >>"$OUT"
echo "Report written to: $OUT"
echo
cat "$OUT"
